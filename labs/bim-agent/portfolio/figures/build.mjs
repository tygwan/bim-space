// Generates pipeline.svg (figure B) and schema.svg (figure C) from the tables below, so every chip, pill and card
// shares one grid and one row template. architecture.svg (figure A) is drawn by hand.
// Sources: notes/architecture.md 2, notes/data-schema.md, src/BimAgent.Core/Contracts (field names as in code).
//   node labs/bim-agent/portfolio/figures/build.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sans = "Pretendard, 'Malgun Gothic', 'Apple SD Gothic Neo', 'Noto Sans KR', sans-serif";
const mono = "'Cascadia Mono', Consolas, 'D2Coding', monospace";
const C = {
  ink: "#1B2430", muted: "#5B6675", line: "#D5DBE3", faint: "#EEF1F5", band: "#F1F3F6",
  fact: "#6B7380", infer: "#2F6FEB", verdict: "#D9891A", verdictInk: "#A85F00", verdictBg: "#FFF5E6", host: "#2B313A",
};
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const text = (x, y, s, attrs = "") => `<text x="${x}" y="${y}" ${attrs}>${esc(s)}</text>`;
const markers = `<defs>
  <marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${C.muted}"/></marker>
  <marker id="v" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${C.verdict}"/></marker>
</defs>`;
const svg = (w, h, body, note) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" font-family="${sans}">\n  <!-- ${note} Generated by build.mjs; edit the tables there. -->\n${markers}\n${body}\n</svg>\n`;

// ---------- Figure B: pipeline ----------
{
  const stages = [
    ["모델 읽기", "객체 · 속성 전부", "raw-snapshot", "host"],
    ["물리 객체", "형상 단위 묶기", "planning-universe", "infer"],
    ["모델 현황", "객체 수 · 계층", "intake-summary", "infer"],
    ["속성 표준화", "항목별 신뢰도", "canonical-model", "infer"],
    ["데이터 준비도", "항목별 점수", "quality-report", "infer"],
    ["의미 관계", "계통 · 라인 · 공간", "semantic-graph", "infer"],
    ["형상 인접", "bbox 접촉 · 근접", "adjacency-aggregate", "infer"],
    ["연결 관계", "신뢰도 0.85 + 검토", "connectivity-graph", "infer"],
    ["일정 초안", "순서 결정 기준", "schedule-candidates", "infer"],
    ["선후 관계", "CPM 주공정", "leaf-schedule-network", "infer"],
    ["TimeLiner", "세트 · 작업 반영", "세트 · 작업 594", "host"],
  ];
  const left = 104, w = 141, gap = 12, step = w + gap;
  const x = (i) => left + i * step;
  const right = (i) => x(i) + w;
  const mid = (i) => x(i) + w / 2;
  const rows = { band: [18, 34], chip: [70, 64], pill: [152, 30], human: [212, 58] };
  const out = [];
  const rowLabel = (y, s) => out.push(text(20, y, s, `font-size="12.5" font-weight="700" fill="${C.muted}"`));
  rowLabel(rows.band[0] + 22, "화면");
  rowLabel(rows.chip[0] + 37, "단계");
  rowLabel(rows.pill[0] + 20, "결과 파일");
  rowLabel(rows.human[0] + 34, "검토");

  // Workspace bands
  const band = (a, b, label, small) => {
    out.push(`<rect x="${x(a)}" y="${rows.band[0]}" width="${right(b) - x(a)}" height="${rows.band[1]}" rx="6" fill="${C.band}"/>`);
    out.push(text(x(a) + 14, rows.band[0] + 22, label, `font-size="${small ? 12.5 : 14.5}" font-weight="700" fill="${C.ink}"`));
  };
  band(0, 6, "① 모델 분석");
  band(7, 9, "③ 일정 설계 · 승인");
  band(10, 10, "④ TimeLiner 반영", true);

  // Chips and pills
  stages.forEach(([name, sub, file, kind], i) => {
    const color = kind === "host" ? C.host : C.infer;
    const [cy, ch] = rows.chip;
    out.push(`<rect x="${x(i)}" y="${cy}" width="${w}" height="${ch}" rx="8" fill="#FFFFFF" stroke="${color}" stroke-width="${kind === "host" ? 2 : 1.5}"/>`);
    out.push(`<circle cx="${x(i) + 20}" cy="${cy + 22}" r="11" fill="${color}"/>`);
    out.push(text(x(i) + 20, cy + 26.5, i + 1, `font-size="12" font-weight="700" fill="#FFFFFF" text-anchor="middle"`));
    out.push(text(x(i) + 38, cy + 27, name, `font-size="14.5" font-weight="700" fill="${C.ink}"`));
    out.push(text(x(i) + 14, cy + 50, sub, `font-size="11.5" fill="${C.muted}"`));
    if (i < stages.length - 1) out.push(`<line x1="${right(i)}" y1="${cy + ch / 2}" x2="${x(i + 1) - 2}" y2="${cy + ch / 2}" stroke="${C.muted}" stroke-width="1.5" marker-end="url(#a)"/>`);
    const [py, ph] = rows.pill;
    const last = i === stages.length - 1;
    const fileColor = i === 0 ? C.fact : last ? C.ink : C.infer;
    out.push(`<rect x="${x(i)}" y="${py}" width="${w}" height="${ph}" rx="15" fill="#FFFFFF" stroke="${C.line}"/>`);
    out.push(text(mid(i), py + 19.5, file, `font-family="${last ? sans : mono}" font-size="${last ? 11.5 : file.length > 19 ? 10 : 10.5}" ${last ? 'font-weight="700"' : ""} fill="${fileColor}" text-anchor="middle"`));
  });

  // Human row: verdict loop under stages 7-8, approval gate under stages 10-11
  const [hy, hh] = rows.human;
  const pillBottom = rows.pill[0] + rows.pill[1];
  out.push(`<rect x="${x(6)}" y="${hy}" width="${right(7) - x(6)}" height="${hh}" rx="8" fill="${C.verdictBg}" stroke="${C.verdict}" stroke-width="1.5"/>`);
  out.push(text(x(6) + 14, hy + 23, "② 일정 자격 검토 · 엔지니어 검토", `font-size="14" font-weight="700" fill="${C.ink}"`));
  out.push(text(x(6) + 14, hy + 44, "확인(TRUE)은 연결 확정 · 제외(FALSE)는 제거", `font-size="11.5" fill="${C.verdictInk}"`));
  out.push(`<line x1="${mid(6)}" y1="${pillBottom}" x2="${mid(6)}" y2="${hy - 2}" stroke="${C.muted}" stroke-width="1.5" marker-end="url(#a)"/>`);
  out.push(`<line x1="${mid(7)}" y1="${hy}" x2="${mid(7)}" y2="${pillBottom + 2}" stroke="${C.verdict}" stroke-width="2" marker-end="url(#v)"/>`);
  out.push(`<rect x="${x(9)}" y="${hy}" width="${right(10) - x(9)}" height="${hh}" rx="8" fill="#FFFFFF" stroke="${C.host}" stroke-width="1.5"/>`);
  out.push(text(x(9) + 14, hy + 23, "일정 승인", `font-size="14" font-weight="700" fill="${C.ink}"`));
  out.push(text(x(9) + 14, hy + 44, "승인된 일정만 반영 · plan-approval", `font-size="11.5" fill="${C.muted}"`));
  out.push(`<line x1="${mid(10)}" y1="${hy}" x2="${mid(10)}" y2="${pillBottom + 2}" stroke="${C.muted}" stroke-width="1.5" marker-end="url(#a)"/>`);

  // Legend, one row, on the grid
  const ly = 300;
  const legend = [
    [C.host, "Navisworks 읽기·쓰기", true], [C.fact, "원본 데이터"], [C.infer, "자동 판단(근거 포함)"], [C.verdict, "엔지니어 검토"],
  ];
  let lx = left;
  for (const [color, label, outline] of legend) {
    out.push(outline
      ? `<rect x="${lx}" y="${ly - 11}" width="13" height="13" rx="3" fill="#FFFFFF" stroke="${color}" stroke-width="2"/>`
      : `<rect x="${lx}" y="${ly - 11}" width="13" height="13" rx="3" fill="${color}"/>`);
    out.push(text(lx + 20, ly, label, `font-size="12" fill="${C.muted}"`));
    lx += 44 + [...label].reduce((n, ch) => n + (/[가-힣]/.test(ch) ? 12.5 : 6.8), 0);
  }
  writeFileSync(join(here, "pipeline.svg"), svg(1800, 316, out.map((l) => "  " + l).join("\n"),
    "Figure B: the 11-stage pipeline on one column grid: workspace stage, stage, artifact, human step."));
}

// ---------- Figure C: schema ----------
{
  // Every card: [title, code name, artifact, kind, rows]. Each card has exactly five rows; row 1 is the key.
  const cards = [
    ["원본 객체", "SourceObject", "raw-snapshot", "fact", [
      ["ObjectId", "원본 GUID 키"], ["SourcePath", "선택 트리 경로"], ["IsLeaf", "형상 단위 여부"], ["RawProperty[]", "원본 속성"], ["Geometry", "bbox · OBB"]]],
    ["표준화 객체", "CanonicalObject", "canonical-model", "infer", [
      ["ObjectId", "동일 키"], ["ObjectType", "부재 유형"], ["Area/Zone", "위치"], ["System/LineNumber", "계통 · 라인"], ["SourceEvidence[]", "항목별 근거"]]],
    ["인접 쌍", "AdjacencyPair", "adjacency-aggregate", "infer", [
      ["A/B ObjectId", "객체 쌍"], ["BaseConfidence", "형상 신뢰도"], ["CrossEvidenceFactor", "교차 근거"], ["AggregatedConfidence", "종합 신뢰도"], ["EvidenceTrace[]", "근거 기록"]]],
    ["연결 관계", "ConnectivityGraph", "connectivity-graph", "infer", [
      ["ObjectId", "객체"], ["ExpectedPorts", "기준 포트 수"], ["ActualNeighbors", "검출된 이웃"], ["A/B", "연결"], ["EngineerVerdict", "검토 결과", "verdict"]]],
    ["일정 작업", "ScheduleTask", "schedule-candidates", "infer", [
      ["ObjectIds[]", "포함 객체"], ["GroupKey", "계통 그룹"], ["LeafSequence", "형상 단위 순서"], ["ScheduleLink", "선후 관계"], ["DecisionTrace[]", "판단 근거"]]],
    ["CPM 공정망", "LeafScheduleNode", "leaf-schedule-network", "infer", [
      ["LeafObjectId", "형상 단위 키"], ["ParentTaskId", "소속 작업"], ["Duration", "임시값 1.0"], ["ES/EF/LS/LF", "시작·종료 시각"], ["IsCritical", "주공정 여부"]]],
    ["TimeLiner", "TimelinerTask", "Navisworks 문서", "host", [
      ["Selection", "객체 직접 지정"], ["SelectionSet", "BimAgent/…"], ["PlannedStart/End", "계획 시작·종료"], ["TaskType", "구성"], ["Tasks", "594개"]]],
  ];
  const verdictCard = ["엔지니어 검토", "EdgeVerdict", "verification-decisions", "verdict", [
    ["A/B ObjectId", "검토한 쌍"], ["Verdict", "확인 · 제외"], ["Reason", "사유"], ["Confidence", "신뢰도"], ["EditedAt", "검토 일시"]]];
  const colors = { fact: C.fact, infer: C.infer, verdict: C.verdict, host: C.host };
  const w = 226, gap = 30, step = w + gap, top = 20, headH = 54, rowH = 28, padTop = 10;
  const cardH = headH + padTop + 5 * rowH + 10;
  const out = [];
  const card = (cx, cy, [title, code, file, kind, rows]) => {
    const color = colors[kind];
    out.push(`<rect x="${cx}" y="${cy}" width="${w}" height="${cardH}" rx="8" fill="#FFFFFF" stroke="${color}" stroke-width="${kind === "host" ? 2 : 1.5}"/>`);
    out.push(`<path d="M${cx},${cy + 8} a8,8 0 0 1 8,-8 h${w - 16} a8,8 0 0 1 8,8 v${headH - 8} h-${w} z" fill="${color}"/>`);
    out.push(text(cx + 14, cy + 24, title, `font-size="15" font-weight="700" fill="#FFFFFF"`));
    out.push(text(cx + w - 14, cy + 24, code, `font-family="${mono}" font-size="10.5" fill="#FFFFFF" fill-opacity="0.85" text-anchor="end"`));
    out.push(text(cx + 14, cy + 43, file, `font-family="${kind === "host" ? sans : mono}" font-size="11" fill="#FFFFFF" fill-opacity="0.85"`));
    rows.forEach(([field, meaning, accent], r) => {
      const ry = cy + headH + padTop + r * rowH;
      if (accent === "verdict") out.push(`<rect x="${cx + 6}" y="${ry}" width="${w - 12}" height="${rowH}" rx="5" fill="${C.verdictBg}"/>`);
      else if (r > 0) out.push(`<line x1="${cx + 12}" y1="${ry}" x2="${cx + w - 12}" y2="${ry}" stroke="${C.faint}"/>`);
      const base = ry + 18.5;
      const key = r === 0;
      if (key) out.push(`<circle cx="${cx + 17}" cy="${base - 4}" r="3.5" fill="${C.verdict}"/>`);
      out.push(text(cx + (key ? 26 : 14), base, field, `font-family="${mono}" font-size="11" ${key ? 'font-weight="700"' : ""} fill="${accent === "verdict" ? C.verdictInk : C.ink}"`));
      out.push(text(cx + w - 14, base, meaning, `font-size="11.5" fill="${C.muted}" text-anchor="end"`));
    });
  };
  const cx = (i) => 20 + i * step;
  cards.forEach((c, i) => card(cx(i), top, c));
  const midY = top + headH + padTop + 2.5 * rowH;
  for (let i = 0; i < cards.length - 1; i++) {
    out.push(`<line x1="${cx(i) + w}" y1="${midY}" x2="${cx(i + 1) - 2}" y2="${midY}" stroke="${C.muted}" stroke-width="1.5" marker-end="url(#a)"/>`);
  }
  // Verdict card under the connectivity card, arrow straight up into it
  const vy = top + cardH + 56;
  card(cx(3), vy, verdictCard);
  out.push(`<line x1="${cx(3) + w / 2}" y1="${vy}" x2="${cx(3) + w / 2}" y2="${top + cardH + 2}" stroke="${C.verdict}" stroke-width="2" marker-end="url(#v)"/>`);
  out.push(text(cx(3) + w / 2 + 10, top + cardH + 33, "다음 계산 때 연결에 반영", `font-size="11.5" fill="${C.verdictInk}"`));

  // Reading notes, left of the verdict card, on the same rows
  const nx = cx(0), ny = vy + 12;
  const legend = [[C.fact, "원본 데이터 · 해석해도 바뀌지 않음"], [C.infer, "자동 판단 · 값마다 근거"], [C.verdict, "엔지니어 검토 · 따로 저장"], [C.host, "Navisworks에 반영하는 결과"]];
  legend.forEach(([color, label], i) => {
    out.push(`<rect x="${nx}" y="${ny + i * 30}" width="14" height="14" rx="3" fill="${color}"/>`);
    out.push(text(nx + 24, ny + i * 30 + 12, label, `font-size="12.5" fill="${C.ink}"`));
  });
  out.push(`<circle cx="${nx + 7}" cy="${ny + 4 * 30 + 16}" r="4" fill="${C.verdict}"/>`);
  out.push(text(nx + 24, ny + 4 * 30 + 20, "키 · ObjectId = 원본 GUID(LcOaNodeGuid)", `font-size="12.5" font-weight="700" fill="${C.ink}"`));
  out.push(text(nx + 24, ny + 4 * 30 + 40, "모든 결과 파일을 이 키로 이어, PC가 바뀌어도 같은 결과가 나온다", `font-size="12" fill="${C.muted}"`));
  const height = vy + cardH + 20;
  writeFileSync(join(here, "schema.svg"), svg(1800, height, out.map((l) => "  " + l).join("\n"),
    "Figure C: the main contracts, five rows each (row 1 is the key), and the verdict that feeds the connectivity edges."));
}
console.log("wrote pipeline.svg, schema.svg");
